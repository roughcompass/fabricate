test("states that intents go to an AI model before New prototype's first field (Composer notice)", async ({ page, db: _db }) => {
  await page.goto("/prototypes/new");
  const notice = page.locator("[data-ai-notice]");
  await expect(notice).toContainText("Prototypes are generated by AI and contain fictional data only.");
  await expect(notice).toContainText("don't include client or confidential information");
  const order = await page.evaluate(() => {
    const noticeElement = document.querySelector("[data-ai-notice]")!;
    const firstField = document.querySelector("main input:not([type=hidden]), main textarea")!;
    return noticeElement.compareDocumentPosition(firstField) & Node.DOCUMENT_POSITION_FOLLOWING;
  });
  expect(order).toBeTruthy();
});

