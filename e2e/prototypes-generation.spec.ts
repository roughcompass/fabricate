test("refines version 2 of 4 into version 5, and keeps sending unavailable while a refinement runs (Viewing an earlier version; Refinement in progress)", async ({ page, db: _db }) => {
  await generate(page, { intent: INTENT, personas: ["Maya Lindqvist"], variants: 1 });
  await page.getByRole("button", { name: "Keep" }).click();
  await page.getByRole("link", { name: "Exception-first queue" }).click();
  await page.waitForURL(/\/prototypes\/pro_[a-z0-9]{16}$/);
  const prototype = page.url();
  for (const [index, message] of ["Group by cut-off time", "Show the total per group", "Add a confirm step for large amounts"].entries()) {
    await page.getByLabel(/Ask for a change/).fill(message);
    await page.getByRole("button", { name: "Send" }).click();
    await expect(page.getByLabel(/Ask for a change/)).toBeDisabled();
    await expect(page.locator(`[data-version-chip='${index + 2}']`)).toBeVisible({ timeout: 30_000 });
    await expect(page.getByLabel(/Ask for a change/)).toBeEnabled({ timeout: 30_000 });
  }
  await page.goto(`${prototype}?v=2`);
  await expect(page.locator("[data-version-label]")).toHaveText("Version 2 of 4");
  await page.getByLabel("Ask for a change to version 2").fill("Group by cut-off time and show the total per group");
  await page.getByRole("button", { name: "Send" }).click();
  await expect(page.locator("[data-version-chip='5']")).toBeVisible({ timeout: 30_000 });
  await page.getByRole("link", { name: "Provenance" }).click();
  await expect(page.locator("[data-provenance]")).toContainText("Group by cut-off time and show the total per group");
  await expect(page.locator("[data-provenance]").getByRole("link", { name: "v2" })).toBeVisible();
});

