test("deletes a generation, keeping the prototype kept from it (Deleting a generation)", async ({ page, db: _db }) => {
  await generate(page, { intent: INTENT, personas: ["Maya Lindqvist"], variants: 2 });
  await page.locator("[data-prototype-variant]").first().getByRole("button", { name: "Keep" }).click();
  await expect(page.getByText(/Kept as/).first()).toBeVisible();
  const generation = page.url().split("?")[0]!;
  // A fresh load, so no refresh after Keep closes the dialog.
  await page.goto(generation);
  await page.getByRole("button", { name: "Delete generation" }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Delete generation" }).click();
  await page.waitForURL(/\/prototypes\?notice=generation-deleted/);
  await expect(page.getByRole("region", { name: "Notifications" }).getByText("The generation was deleted.")).toBeVisible();
  await expect(page.locator("[data-prototype]")).toHaveCount(1);
  await expect(page.locator("[data-open-generation]")).toHaveCount(0);
  expect((await page.request.get(generation)).status()).toBe(404);
  await page.locator("[data-prototype]").getByRole("link").first().click();
  await expect(page.getByRole("link", { name: "See the variants it was kept from" })).toHaveCount(0);
});
