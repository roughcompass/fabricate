test("resets Prototypes to the seeded examples: share links answer not found, and accepted templates remain (Resetting)", async ({ page, browser, db: _db }) => {
  await keepOne(page);
  await acceptTemplate(page, { title: "Urgent payments queue" });
  const address = await share(page);

  await page.goto("/prototypes");
  await expect(page.getByRole("link", { name: "Exception-first queue" })).toBeVisible();
  await page.getByRole("button", { name: "More actions" }).click();
  await page.getByRole("button", { name: "Reset Prototypes" }).click();
  await page.getByRole("dialog", { name: "Reset Prototypes?" }).getByRole("button", { name: "Reset Prototypes" }).click();
  await expect(page.getByRole("region", { name: "Notifications" }).getByText("Prototypes was reset.")).toBeVisible();
  await expect(page.getByRole("link", { name: "Exception-first queue" })).toHaveCount(0);

  const recipient = await browser.newContext();
  try {
    expect((await (await recipient.newPage()).goto(address))?.status()).toBe(404);
  } finally {
    await recipient.close();
  }
  await page.goto("/templates?origin=prototypes");
  await expect(page.getByRole("link", { name: "Urgent payments queue" })).toBeVisible();
});

