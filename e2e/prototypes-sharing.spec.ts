// prototypes/sharing-and-export spec: share links and revoking them; page-shell
// spec: the Page shell form, and share links keeping their shell.

/** Creates a share link to the version shown and returns its address. */
async function share(page: import("@playwright/test").Page): Promise<string> {
  await page.getByText("Share or download").click();
  await page.getByRole("button", { name: /^Share v\d+$/ }).click();
  const link = page.locator("[data-share-link] code");
  await expect(link).toHaveText(/\/p\/[A-Za-z0-9_-]{43}$/);
  return (await link.textContent())!;
}

test("opens a share link in a private window with the version, its checks, and its fit, and nothing else (Opening a share link in another browser)", async ({ page, browser, db: _db }) => {
  await keepOne(page);
  const address = await share(page);
  const recipient = await browser.newContext();
  try {
    const shared = await recipient.newPage();
    await shared.goto(address);
    await expect(shared.locator("[data-shared-prototype]")).toContainText("A read-only view of Exception-first queue v1");
    await expect(shared.locator("[data-check-summary]")).toContainText("Checks passed");
    await expect(shared.locator("[data-checks-panel]")).toContainText("Maya Lindqvist");
    await expect(shared.locator("[data-ai-notice]")).toContainText("Prototypes are generated by AI and contain fictional data only.");
    await waitForFrame(shared);
    await expect(previewFrame(shared).getByRole("banner")).toContainText("Meridian Corporate Banking");
    await shared.getByRole("group", { name: "Mode" }).getByRole("button", { name: "Dark" }).click();
    await expect(previewFrame(shared).locator("html")).toHaveAttribute("data-mode", "dark");
    // No feedback, refinement, or other versions.
    await expect(shared.getByRole("textbox", { name: /Ask for a change/ })).toHaveCount(0);
    await expect(shared.getByRole("group", { name: "Rate this version" })).toHaveCount(0);
    await expect(shared.getByRole("link", { name: /Version/ })).toHaveCount(0);
  } finally {
    await recipient.close();
  }
});

test("answers not found for a revoked link, and the not-found page links only to pages that exist (Revoking)", async ({ page, browser, db: _db }) => {
  await keepOne(page);
  const address = await share(page);
  await expect(page.locator("[data-share]")).toHaveCount(1);
  await page.getByRole("button", { name: "Revoke" }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Revoke link" }).click();
  await expect(page.getByRole("region", { name: "Notifications" }).getByText("The share link was revoked.")).toBeVisible();
  await expect(page.locator("[data-share]")).toHaveCount(0);

  const recipient = await browser.newContext();
  try {
    const shared = await recipient.newPage();
    const response = await shared.goto(address);
    expect(response?.status()).toBe(404);
    await expect(shared.getByRole("heading", { level: 1 })).toContainText(/not found/i);
    expect((await shared.request.get(`${address}/render`)).status()).toBe(404);
    const links = await shared.locator("main a[href^='/']").evaluateAll((anchors) => anchors.map((anchor) => anchor.getAttribute("href")!));
    expect(links.length).toBeGreaterThan(0);
    for (const href of new Set(links)) expect((await shared.request.get(href)).status(), href).toBeLessThan(400);
  } finally {
    await recipient.close();
  }
});

test("renames the application in the Page shell, which previews show but an existing share keeps (Shell changed after sharing; Editing the shell)", async ({ page, browser, db: _db }) => {
  const prototype = await keepOne(page);
  const address = await share(page);

  await page.goto("/prototypes/shell");
  await expect(page.getByRole("heading", { level: 1, name: "Page shell" })).toBeVisible();
  await page.getByLabel("Application name").fill("Treasury Hub");
  const nav = page.getByLabel("Navigation items");
  await nav.fill(`${await nav.inputValue()}\nCards: Limits, Statements`);
  await page.getByRole("button", { name: "Save shell" }).click();
  await expect(page.getByRole("region", { name: "Notifications" }).getByText("The page shell was saved.")).toBeVisible();

  await page.goto(prototype);
  await waitForFrame(page);
  await expect(previewFrame(page).getByRole("banner")).toContainText("Treasury Hub");
  await expect(previewFrame(page).getByRole("navigation").first()).toContainText("Cards");

  const recipient = await browser.newContext();
  try {
    const shared = await recipient.newPage();
    await shared.goto(address);
    await waitForFrame(shared);
    await expect(previewFrame(shared).getByRole("banner")).toContainText("Meridian Corporate Banking");
    await expect(previewFrame(shared).getByRole("navigation").first()).not.toContainText("Cards");
  } finally {
    await recipient.close();
  }
});

