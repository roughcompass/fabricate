// Prints trigger SQL that enforces the state machines in
// src/lib/db/state-machines.ts. When a machine changes, write the output to a
// new custom migration:
//
//   npx drizzle-kit generate --custom --name <name>
//   npx tsx scripts/state-machine-triggers.ts > drizzle/<that file>.sql
//
// The first version is drizzle/0010_state_machines.sql. Each breakpoint chunk
// holds exactly one statement, as Drizzle's migrator requires.
import {
  RUN_MACHINE,
  EVALUATION_MACHINE,
  EVALUATION_RELEASE_MACHINE,
  SURVEY_MACHINE,
  type StateMachine,
  TARGET_MACHINE,
} from "../src/lib/db/state-machines";

const list = (values: readonly string[]) => values.map((value) => `'${value}'`).join(", ");

function triggers<S extends string>(table: string, noun: string, machine: StateMachine<S>): string[] {
  const allowed = (Object.entries(machine.transitions) as [S, S[]][])
    .filter(([, targets]) => targets.length > 0)
    .map(([from, targets]) => `    (OLD.state = '${from}' AND NEW.state IN (${list(targets)}))`)
    .join(" OR\n");
  const singular = noun.replace(/s$/, "");

  return [
    `-- ${machine.name} states: ${Object.keys(machine.transitions).join(", ")}.
CREATE TRIGGER ${table}_initial_state
BEFORE INSERT ON ${table}
WHEN NEW.state IS NOT '${machine.initial}'
BEGIN
  SELECT RAISE(ABORT, '${table}: new ${noun} start ${machine.initial}');
END;`,
    `CREATE TRIGGER ${table}_terminal_frozen
BEFORE UPDATE ON ${table}
WHEN OLD.state IN (${list(machine.terminal)})
BEGIN
  SELECT RAISE(ABORT, '${table}: a terminal ${singular} cannot change');
END;`,
    `CREATE TRIGGER ${table}_state_transitions
BEFORE UPDATE OF state ON ${table}
WHEN NEW.state IS NOT OLD.state AND OLD.state NOT IN (${list(machine.terminal)}) AND NOT (
${allowed}
  )
BEGIN
  SELECT RAISE(ABORT, '${table}: state transition is not allowed');
END;`,
  ];
}

const statements = [
  ...triggers("assessments", "assessments", RUN_MACHINE),
  ...triggers("assessment_targets", "targets", TARGET_MACHINE),
  ...triggers("evaluations", "evaluations", EVALUATION_MACHINE),
  ...triggers("evaluation_releases", "evaluation releases", EVALUATION_RELEASE_MACHINE),
  ...triggers("surveys", "surveys", SURVEY_MACHINE),
];

console.log(
  `-- Generated by scripts/state-machine-triggers.ts from src/lib/db/state-machines.ts.\n` +
    `-- The state machine tests walk every state pair through these triggers.\n` +
    statements.join("\n--> statement-breakpoint\n"),
);
