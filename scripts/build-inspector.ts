// Builds the toolbar's frame agent (add-applications, design decision 6;
// restore-toolbar-tools-and-branch-previews, design decision 6):
//
//   npm run build:inspector
//
// The agent runs inside a running application's framed page, in that
// page's own realm, so it can't be one of the web app's own bundles. esbuild
// bundles src/components/toolbar/inspector/inspector.ts, with its modules and
// the web-vitals library it runs, into one self-contained script at
// public/toolbar/inspector.js, which the Frontend Registry serves like any
// public file. The bundle is committed; test/lint/inspector-bundle.test.ts
// fails when it no longer matches its sources, so run this after changing them
// or upgrading web-vitals or esbuild.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { BuildOptions } from "esbuild";

const ROOT = path.resolve(import.meta.dirname, "..");

export const INSPECTOR_ENTRY = path.join(ROOT, "src/components/toolbar/inspector/inspector.ts");
export const INSPECTOR_BUNDLE = path.join(ROOT, "public/toolbar/inspector.js");

/** The bundle's options; the test builds with them too. */
export const inspectorBuildOptions = {
  entryPoints: [INSPECTOR_ENTRY],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "eof",
  banner: { js: "// The Frontend Registry's frame agent. Generated by scripts/build-inspector.ts from src/components/toolbar/inspector/; don't edit." },
  write: false,
  logLevel: "warning",
} satisfies BuildOptions;

/** The bundle's text, as it would be written. */
export async function buildInspector(): Promise<string> {
  const { build } = await import("esbuild");
  const result = await build(inspectorBuildOptions);
  return result.outputFiles[0]!.text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildInspector();
  fs.mkdirSync(path.dirname(INSPECTOR_BUNDLE), { recursive: true });
  fs.writeFileSync(INSPECTOR_BUNDLE, text);
  console.log(`Wrote ${path.relative(ROOT, INSPECTOR_BUNDLE)} (${text.length} bytes).`);
}
